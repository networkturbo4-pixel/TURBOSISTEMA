function toggleGlobalLayer(layerType, pill) {
    const isActive = pill.classList.toggle('active');
    if (!globalMapInstance || !globalMapInstance.getLayer('layer-points')) return;
    
    if (layerType === 'lines') {
        globalMapInstance.setLayoutProperty('layer-lines', 'visibility', isActive ? 'visible' : 'none');
    } else {
        const activeTypes = [];
        document.querySelectorAll('.map-filter-pill.active').forEach(p => {
            if(p.innerText.includes('NAP')) activeTypes.push('naps');
            if(p.innerText.includes('Mufas')) activeTypes.push('mufas');
        });
        
        let newFilter = ['any', ['in', 'categoryType', ...activeTypes], ['==', 'categoryType', 'other']];
        if (activeTypes.length === 0) newFilter = ['==', 'categoryType', 'none']; 
        
        globalMapInstance.setFilter('layer-points', newFilter);
    }
}

