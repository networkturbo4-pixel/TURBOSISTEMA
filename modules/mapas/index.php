function initCentralMap(geojson, gpsNodes) {
    const mapEl = document.getElementById('globalFiberMap');
    if (!mapEl) return;

    const defaultCenter = [-77.1078046, -11.8475511]; // lng, lat
    
    globalMapInstance = new mapboxgl.Map({
        container: 'globalFiberMap',
        style: 'mapbox://styles/mapbox/satellite-streets-v12',
        center: defaultCenter,
        zoom: 15,
        pitch: 0,
        bearing: 0
    });

    globalMapInstance.addControl(new mapboxgl.NavigationControl(), 'bottom-right');
    
    const hudCoords = document.getElementById('hudCoords');
    const hudZoom = document.getElementById('hudZoom');

    globalMapInstance.on('mousemove', (e) => {
        if (hudCoords && e.lngLat) {
            hudCoords.textContent = `${e.lngLat.lat.toFixed(6)}, ${e.lngLat.lng.toFixed(6)}`;
        }
    });

    globalMapInstance.on('zoom', () => {
        if (hudZoom) hudZoom.textContent = `${globalMapInstance.getZoom().toFixed(1)}x`;
    });

    globalMapInstance.on('load', () => {
        if (!geojson || !geojson.features) return;
        
        let hasCoords = false;
        const bounds = new mapboxgl.LngLatBounds();
        
        geojson.features.forEach(f => {
            const props = f.properties || {};
            const isNap = props.name && props.name.toUpperCase().includes('NAP');
            const isMufa = props.name && props.name.toUpperCase().includes('MUFA');
            
            f.properties.categoryType = isNap ? 'naps' : (isMufa ? 'mufas' : (f.geometry.type === 'LineString' ? 'lines' : 'other'));
            f.properties.color = isNap ? '#facc15' : (isMufa ? '#fb923c' : (props.color || '#38bdf8'));
            
            if (f.geometry.type === 'Point') {
                bounds.extend(f.geometry.coordinates);
                hasCoords = true;
            } else if (f.geometry.type === 'LineString') {
                f.geometry.coordinates.forEach(c => bounds.extend(c));
                hasCoords = true;
            }
        });

        globalMapInstance.addSource('fiber-network', {
            type: 'geojson',
            data: geojson
        });

        globalMapInstance.addLayer({
            id: 'layer-lines',
            type: 'line',
            source: 'fiber-network',
            filter: ['==', 'categoryType', 'lines'],
            paint: {
                'line-color': ['get', 'color'],
                'line-width': 4,
                'line-opacity': 0.9
            }
        });

        globalMapInstance.addLayer({
            id: 'layer-points',
            type: 'circle',
            source: 'fiber-network',
            filter: ['!=', 'categoryType', 'lines'],
            paint: {
                'circle-color': ['get', 'color'],
                'circle-radius': 7,
                'circle-stroke-color': '#ffffff',
                'circle-stroke-width': 2
            }
        });

        if (hasCoords) {
            globalMapInstance.fitBounds(bounds, { padding: 50 });
        }

        const hudVisible = document.getElementById('hudVisibleNodes');
        if (hudVisible) {
            const nodesCount = geojson.features.filter(f => f.geometry.type === 'Point').length;
            hudVisible.textContent = nodesCount;
        }

        globalMapInstance.on('click', 'layer-points', (e) => {
            if (!e.features.length) return;
            const feature = e.features[0];
            const pos = feature.geometry.coordinates;
            showNodePopover(feature.properties, {lat: pos[1], lng: pos[0]});
        });

        globalMapInstance.on('mouseenter', 'layer-points', () => {
            globalMapInstance.getCanvas().style.cursor = 'pointer';
        });
        globalMapInstance.on('mouseleave', 'layer-points', () => {
            globalMapInstance.getCanvas().style.cursor = '';
        });
    });
}

